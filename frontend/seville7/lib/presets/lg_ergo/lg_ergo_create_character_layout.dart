Map<String, GridSlot> _bodyPartSlots() => {
  for (final part in _bodyParts)
    part.name: GridSlot(
      row: 'canvas',
      column: 'canvas',
      rowOffset: part.y / 2048,
      columnOffset: part.x / 1024,
      rowSpan: part.height / 2048,
      columnSpan: part.width / 1024,
    ),
};

Map<String, PanelLayout> _bodyPartPanels() => {
  for (final part in _bodyParts)
    part.name: PanelLayout(
      slot: part.name,
      aliases: ['body-part', 'character-${part.name}'],
      text: const LayoutTextConfig(value: LayoutText.none()),
      background: [
        LayoutBackground.svg(
          assetPath: 'assets/icons/vector/body-parts/${part.asset}',
          fit: LayoutBackgroundFit.fill,
          rotationDegrees: part.rotationDegrees,
          flipHorizontally: part.flipHorizontally,
        ),
      ],
    ),
};
